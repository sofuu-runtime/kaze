#!/usr/bin/env bash
# self-sync.sh -- keep kaze/compiler/kaze_self.kaze equal to the sum of its parts.
#
# The self-hosted compiler is authored as small modules and also needs to
# exist as one file, because that is the unit the bootstrap compiles. Rather
# than maintain two copies, this script derives the monolith and can prove it
# is current.
#
#   scripts/self-sync.sh           rewrite kaze_self.kaze
#   scripts/self-sync.sh --check   exit 1 if it is stale
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PARTS="compiler/token.kaze compiler/ast.kaze compiler/lexer.kaze compiler/parser.kaze compiler/checker.kaze compiler/module.kaze compiler/isa.kaze compiler/machine.kaze compiler/ir.kaze compiler/qbe_codegen.kaze compiler/codegen.kaze compiler/lsp.kaze compiler/main.kaze"
OUT="compiler/kaze_self.kaze"

build() {
    echo "# kaze_self.kaze -- the self-hosted Kaze compiler as one file."
    echo "#"
    echo "# Generated by scripts/self-sync.sh from compiler/{token,ast,lexer,parser,checker,module,isa,machine,ir,qbe_codegen,codegen,lsp,main}.kaze."
    echo "# Edit the modules, never this file. The use lines are dropped because the"
    echo "# loader is not available inside the compiler's own bootstrap."
    echo ""
    for part in $PARTS; do
        grep -v '^use "' "$part"
        echo ""
    done
}

if [ "${1:-}" = "--check" ]; then
    if diff -q <(build) "$OUT" >/dev/null 2>&1; then
        echo "self-sync: $OUT is current"
    else
        echo "self-sync: $OUT is STALE; run scripts/self-sync.sh" >&2
        exit 1
    fi
else
    build > "$OUT"
    echo "self-sync: wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
fi