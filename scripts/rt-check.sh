    if "$CLANG" -target i386-none-elf -ffreestanding -isystem "$TMP/freestanding" $STRICT -fsyntax-only "$LIBM" >"$TMP/i386.log" 2>&1 \
        && "$CLANG" -target i386-none-elf -ffreestanding -isystem "$TMP/freestanding" $STRICT -I "$DIST" -fsyntax-only "$TMP/type_probe32.c" >>"$TMP/i386.log" 2>&1; then
        M32_SYNTAX_OK=1
        pass "i386 freestanding syntax" "kaze_rt.c parses for bare i386 against stub libc headers"
    else
        fail "i386 freestanding syntax" "the i386 freestanding parse failed"
        show_log "$TMP/i386.log"
    fi
else
    skip "i386 freestanding syntax" "the freestanding cross-target parse needs clang; this compiler is $CLANG_LINE"
fi

if [ "$M32_RAN" -eq 1 ]; then
    M32_PARTS="a 32-bit binary built and passed the behavioural gate"
else
    M32_PARTS="no 32-bit binary executed on this host"
    if [ "$M32_OBJ_OK" -eq 1 ]; then
        M32_PARTS="$M32_PARTS; 32-bit object codegen passed"
    fi
    if [ "$M32_SYNTAX_OK" -eq 1 ]; then
        M32_PARTS="$M32_PARTS; freestanding i386 syntax passed"
    fi
fi

# ---------------------------------------------------------------------------
# Sanitizers: one million arena cycles plus the whole behavioural suite under
# AddressSanitizer and UndefinedBehaviorSanitizer.
# ---------------------------------------------------------------------------

LEAK_SUPPORT=no
LEAK_REASON="LeakSanitizer could not be built on this host"
printf 'int main(void) { return 0; }\n' > "$TMP/leak_probe.c"
if "$CLANG" $SAN_FLAGS "$TMP/leak_probe.c" -o "$TMP/leak_probe" >"$TMP/leak_build.log" 2>&1; then
    # A nested shell contains the job-control notice: on hosts without
    # LeakSanitizer, asking for detect_leaks=1 aborts the probe by design, and
    # that diagnostic belongs in the log, not on the terminal.
    bash -c 'ASAN_OPTIONS=detect_leaks=1 "$1" 2>&1; exit 0' kaze-leak-probe "$TMP/leak_probe" >"$TMP/leak_probe.log" 2>&1
    if grep -q 'detect_leaks is not supported' "$TMP/leak_probe.log"; then
        LEAK_SUPPORT=no
        LEAK_REASON="$(grep -m1 'detect_leaks is not supported' "$TMP/leak_probe.log" | cut -c1-150)"
    else
        LEAK_SUPPORT=yes
        LEAK_REASON="LeakSanitizer is available on this host"
    fi
fi

run_sanitized() {
    local bin="$1"
    local log="$2"
    if [ "$LEAK_SUPPORT" = "yes" ]; then
        ASAN_OPTIONS=detect_leaks=1 UBSAN_OPTIONS=print_stacktrace=1:halt_on_error=1 "$bin" >"$log" 2>&1
    else
        ASAN_OPTIONS=detect_leaks=0 UBSAN_OPTIONS=print_stacktrace=1:halt_on_error=1 "$bin" >"$log" 2>&1
    fi
}

if "$CLANG" $SAN_FLAGS -I "$DIST" "$LIBM" "$TMP/rt_test.c" -o "$TMP/rt_test_asan" >"$TMP/asan_build.log" 2>&1; then
    if run_sanitized "$TMP/rt_test_asan" "$TMP/asan_test.log"; then
        if sanitizer_reports "$TMP/asan_test.log"; then
            fail "ASan/UBSan behaviour" "a sanitizer reported a problem"
            grep -E 'ERROR|runtime error|SUMMARY' "$TMP/asan_test.log" | head -n 10 | sed 's/^/      | /'
        else
            pass "ASan/UBSan behaviour" "$(grep -c '^ok' "$TMP/asan_test.log") checks, no sanitizer report"
        fi
    else
        fail "ASan/UBSan behaviour" "the instrumented behavioural gate failed"
        show_log "$TMP/asan_test.log"
    fi
else
    fail "ASan/UBSan behaviour" "the instrumented build failed"
    show_log "$TMP/asan_build.log"
fi

if "$CLANG" $SAN_FLAGS -I "$DIST" "$LIBM" "$TMP/rt_asan.c" -o "$TMP/rt_asan_bin" >"$TMP/asan_loop_build.log" 2>&1; then
    if run_sanitized "$TMP/rt_asan_bin" "$TMP/asan_loop.log"; then
        if sanitizer_reports "$TMP/asan_loop.log"; then
            fail "ASan/UBSan 1e6 arena cycles" "a sanitizer reported a problem"
            grep -E 'ERROR|runtime error|SUMMARY' "$TMP/asan_loop.log" | head -n 10 | sed 's/^/      | /'
        else
            pass "ASan/UBSan 1e6 arena cycles" "1000000 alloc+reset cycles, no sanitizer report"
        fi
        grep -E '^# asan' "$TMP/asan_loop.log" | sed 's/^/      | /'
    else
        fail "ASan/UBSan 1e6 arena cycles" "the loop failed"
        show_log "$TMP/asan_loop.log"
    fi
else
    fail "ASan/UBSan 1e6 arena cycles" "the instrumented build failed"
    show_log "$TMP/asan_loop_build.log"
fi

if [ "$LEAK_SUPPORT" = "yes" ]; then
    pass "leak detection" "ASAN_OPTIONS=detect_leaks=1 ran with zero leak reports"
    LEAK_LINE="LeakSanitizer (detect_leaks=1) reported zero leaks"
else
    skip "leak detection (LSan)" "$LEAK_REASON"
    LEAK_LINE="LeakSanitizer unsupported on this host; the arena's heap bytes were counted instead (see the asan heap line above)"
fi

# ---------------------------------------------------------------------------
# Verdict.
# ---------------------------------------------------------------------------

printf '\n'
if [ "$FAILED" -ne 0 ]; then
    printf 'rt-check: FAIL - %d passed, %d skipped, %d failed\n' "$PASSED" "$SKIPPED" "$FAILED"
    printf 'rt-check: 32-bit: %s\n' "$M32_PARTS"
    printf 'rt-check: leak detection: %s\n' "$LEAK_LINE"
    exit 1
fi
printf 'rt-check: PASS - %d passed, %d skipped, 0 failed\n' "$PASSED" "$SKIPPED"
printf 'rt-check: 32-bit: %s\n' "$M32_PARTS"
printf 'rt-check: leak detection: %s\n' "$LEAK_LINE"
printf 'rt-check: 64-bit execution and the sanitizer runs above are what this host measured.\n'
exit 0
