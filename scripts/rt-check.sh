#!/usr/bin/env bash
# scripts/rt-check.sh - the Phase 1 gate for the Kaze C99 runtime substrate.
#
# Roadmap Phase 1 acceptance gates, made executable:
#   1. kaze_rt.h and kaze_rt.c compile with zero warnings under
#      clang -std=c99 -Wall -Wextra -Werror -pedantic, and under gcc when a
#      gcc is actually present.
#   2. The same sources compile for a 32-bit target, and this script states
#      exactly how far that verification went on this host.
#   3. One million arena alloc + bulk-reset cycles run clean under
#      AddressSanitizer and UndefinedBehaviorSanitizer.
#   4. The trapped behaviours are asserted: integer overflow, divide by zero,
#      OOM, the 1500 ms watchdog boundary, container round-trips, and the
#      signal cleanup registry.
#
# Every gate prints one PASS, FAIL or SKIP line. A SKIP is not a pass: it means
# the host cannot verify that property (no GNU gcc, no 32-bit SDK, no
# LeakSanitizer). Exit status is 0 only when every check that ran passed, 1 when
# any check failed, and 2 when no C compiler was found at all.
#
# Usage: scripts/rt-check.sh [--verbose]
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIST="$ROOT/dist"
LIBM="$DIST/kaze_rt.c"
LIBH="$DIST/kaze_rt.h"
STRICT="-std=c99 -Wall -Wextra -Werror -pedantic"
SAN_FLAGS="-std=c99 -Wall -Wextra -Werror -pedantic -g -O1 -fsanitize=address,undefined -fno-omit-frame-pointer"

VERBOSE=0
if [ "$#" -gt 0 ] && [ "$1" = "--verbose" ]; then
    VERBOSE=1
fi

PASSED=0
FAILED=0
SKIPPED=0

pass() { PASSED=$((PASSED + 1)); printf 'PASS  %-34s %s\n' "$1" "$2"; }
fail() { FAILED=$((FAILED + 1)); printf 'FAIL  %-34s %s\n' "$1" "$2"; }
skip() { SKIPPED=$((SKIPPED + 1)); printf 'SKIP  %-34s %s\n' "$1" "$2"; }
note() { printf 'NOTE  %-34s %s\n' "$1" "$2"; }

show_log() {
    if [ "$VERBOSE" -eq 1 ]; then
        sed 's/^/      | /' "$1"
    else
        tail -n 15 "$1" | sed 's/^/      | /'
    fi
}

evidence() {
    if [ "$VERBOSE" -eq 1 ]; then
        sed 's/^/      | /' "$1"
    else
        grep -E '^# ' "$1" | sed 's/^/      | /'
    fi
}

sanitizer_reports() {
    grep -qE 'ERROR: (AddressSanitizer|LeakSanitizer)|runtime error:|SUMMARY: (AddressSanitizer|UndefinedBehaviorSanitizer)' "$1"
}

TMP="$(mktemp -d /tmp/kaze-rt-check.XXXXXX)"
if [ ! -d "$TMP" ]; then
    printf 'rt-check: cannot create a temporary directory\n'
    exit 2
fi
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT

CLANG="$(command -v clang 2>/dev/null)"
if [ -z "$CLANG" ]; then
    CLANG="$(command -v cc 2>/dev/null)"
fi
GCC="$(command -v gcc 2>/dev/null)"
CLANGPP="$(command -v clang++ 2>/dev/null)"

if [ -z "$CLANG" ]; then
    printf 'SKIP  %-34s %s\n' "no C compiler" "looked for clang and cc on PATH"
    printf 'rt-check: SKIP is not a pass; install clang or gcc and rerun.\n'
    exit 2
fi

CLANG_LINE="$("$CLANG" --version 2>/dev/null | head -n 1)"
CLANG_IS_CLANG=0
case "$CLANG_LINE" in
    *clang*|*Clang*) CLANG_IS_CLANG=1 ;;
esac

printf 'rt-check: %s on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(uname -srm)"
printf 'rt-check: clang: %s\n' "$CLANG_LINE"
printf 'rt-check: sources: %s\n' "$DIST/kaze_rt.h $DIST/kaze_rt.c"
printf '\n'

# ---------------------------------------------------------------------------
# Test programs. They are generated here so the gate owns its own harness and
# the shipped dist/ directory stays exactly two files.
# ---------------------------------------------------------------------------

cat > "$TMP/rt_test.c" <<'KAZE_RT_TEST_C'
/* rt_test.c — behavioural gate for the Kaze C99 runtime substrate.
 *
 * This file is generated by scripts/rt-check.sh into a temporary directory; it
 * is not part of the shipped runtime. It exercises the contract that the
 * roadmap Phase 1 gates name: arena alloc/reset semantics, OOM as a structured
 * trap, checked arithmetic boundaries, value round-trips, the 1500 ms watchdog,
 * and signal-time cleanup registration. Each check prints one line; the
 * process exit status is the number of failed checks (0 on success).
 */
#include "kaze_rt.h"

static int checks = 0;
static int failures = 0;

static void check(bool cond, const char *name)
{
    checks++;
    if (cond) {
        printf("ok %d - %s\n", checks, name);
    } else {
        failures++;
        printf("not ok %d - %s\n", checks, name);
    }
}

/* One capture buffer, one trap at a time: the runtime calls the handler
 * synchronously, so a single slot is enough to assert the code string. */
static char last_code[32];
static char last_message[192];
static int trap_count = 0;

static int capture_handler(const char *code, const char *message)
{
    size_t i = 0;
    trap_count++;
    while (code != NULL && code[i] != '\0' && i + 1u < sizeof last_code) {
        last_code[i] = code[i];
        i++;
    }
    last_code[i] = '\0';
    i = 0;
    while (message != NULL && message[i] != '\0' && i + 1u < sizeof last_message) {
        last_message[i] = message[i];
        i++;
    }
    last_message[i] = '\0';
    return 1;
}

static void reset_capture(void)
{
    last_code[0] = '\0';
    last_message[0] = '\0';
    trap_count = 0;
}

static bool trapped_with(const char *code)
{
    return trap_count == 1 && strcmp(last_code, code) == 0;
}

