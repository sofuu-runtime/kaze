run_behavioural() {
    local name="$1"
    local cc="$2"
    local display="$1"
    local cc_line
    cc_line="$("$cc" --version 2>/dev/null | head -n 1)"
    if [ "$name" = "gcc" ]; then
        case "$cc_line" in
            *clang*|*Clang*) display="gcc-alias(clang)" ;;
        esac
    fi
    if [ "$name" = "clang" ] && [ "$CLANG_IS_CLANG" -eq 0 ]; then
        display="primary-cc(not clang)"
    fi

    if ! "$cc" $STRICT -O2 -I "$DIST" "$LIBM" "$TMP/rt_test.c" -o "$TMP/rt_test_$name" >"$TMP/build_$name.log" 2>&1; then
        fail "$display 64-bit build" "rejected under $STRICT"
        show_log "$TMP/build_$name.log"
        return
    fi
    pass "$display 64-bit build" "zero warnings under $STRICT"
    note "$display identity" "$cc_line"

    if ! "$TMP/rt_test_$name" >"$TMP/run_$name.log" 2>&1; then
        fail "$display 64-bit behaviour" "the behavioural gate failed"
        grep -E '^not ok|^# ' "$TMP/run_$name.log" | head -n 25 | sed 's/^/      | /'
        return
    fi
    pass "$display 64-bit behaviour" "$(grep -c '^ok' "$TMP/run_$name.log") checks passed"
    evidence "$TMP/run_$name.log"
}

