static void test_clock_and_watchdog(void)
{
    uint64_t t0 = kaze_time_ms();
    uint64_t t1 = kaze_time_ms();
    kaze_watchdog_t wd;
    kaze_code_t code;

    check(t1 >= t0, "kaze_time_ms never runs backwards");
    {
        uint64_t start = kaze_time_ms();
        uint64_t now = start;
        while (now - start < 3u) {
            now = kaze_time_ms();
        }
        check(now - start >= 3u && now - start < 2000u,
              "kaze_time_ms advances across a real 3 ms interval");
    }

    kaze_watchdog_init(&wd, 0);
    check(wd.timeout_ms == (uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS,
          "watchdog_init(0) selects the 1500 ms default");
    check(!kaze_watchdog_stale(&wd), "a freshly armed watchdog is not stale");

    /* Boundary checks are exact only if the clock has advanced past the
     * timeout at least once; on any hosted machine running a test suite it
     * has, and the skip line keeps a cold-boot run honest. */
    if (kaze_time_ms() >= (uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS) {
        wd.timeout_ms = (uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS;
        wd.last_packet_ms = kaze_time_ms() - ((uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS - 1u);
        check(!kaze_watchdog_stale(&wd), "1499 ms since the last packet is still fresh");
        wd.last_packet_ms = kaze_time_ms() - (uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS;
        check(kaze_watchdog_stale(&wd), "exactly 1500 ms since the last packet is stale");
        wd.last_packet_ms = kaze_time_ms() - ((uint64_t)KAZE_HEARTBEAT_TIMEOUT_MS + 250u);
        reset_capture();
        code = kaze_watchdog_abort_if_stale(&wd);
        check(code == KAZE_ERR_SAFETY_VIOLATION,
              "abort_if_stale returns KAZE_ERR_SAFETY_VIOLATION");
        check(trapped_with("E_SAFETY_VIOLATION"),
              "the handler receives the E_SAFETY_VIOLATION code");
        check(kaze_code_name(KAZE_ERR_SAFETY_VIOLATION) != NULL &&
                  strcmp(kaze_code_name(KAZE_ERR_SAFETY_VIOLATION), "E_SAFETY_VIOLATION") == 0,
              "kaze_code_name spells E_SAFETY_VIOLATION exactly");
    } else {
        printf("# skip - clock base is under 1500 ms, boundary checks need a warmer clock\n");
    }

    kaze_watchdog_packet(&wd);
    reset_capture();
    check(kaze_watchdog_abort_if_stale(&wd) == KAZE_OK, "a fresh watchdog returns KAZE_OK");
    check(trap_count == 0, "a fresh watchdog does not trap");

    /* End to end on the real clock: 1600 ms with no packet must trip. */
    {
        uint64_t start = kaze_time_ms();
        while (kaze_time_ms() - start < 1600u) {
            /* spin: the point is to measure the runtime clock, not to sleep */
        }
        check(kaze_watchdog_stale(&wd), "a real 1600 ms gap makes the watchdog stale");
    }
}

