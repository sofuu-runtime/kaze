cat > "$TMP/rt_asan.c" <<'KAZE_RT_ASAN_C'
/* rt_asan.c — sanitizer gate for the Kaze C99 runtime substrate.
 *
 * One million arena allocation + bulk-reset cycles under ASan/UBSan, plus a
 * periodic container build so the map and vector code is instrumented too.
 * Generated by scripts/rt-check.sh into a temporary directory.
 */
#include "kaze_rt.h"

/* LeakSanitizer is unavailable on some hosts (arm64 macOS among them). Where
 * the sanitizer allocator interface exists, measure the resident heap bytes
 * around the arena's lifetime instead: the runtime's only malloc is
 * kaze_arena_init_heap, so returning to the baseline is a direct proof that
 * the arena leaked nothing. */
#if defined(__has_include)
#if __has_include(<sanitizer/allocator_interface.h>)
#include <sanitizer/allocator_interface.h>
#define KAZE_HAVE_ALLOC_IFACE 1
#endif
#endif

#define KAZE_ASAN_CYCLES 1000000ULL

int main(void)
{
    kaze_arena_t arena;
    unsigned long long i;
    unsigned long long container_builds = 0;
    uint64_t started;
    uint64_t elapsed;
#ifdef KAZE_HAVE_ALLOC_IFACE
    unsigned long long baseline = 0;
    unsigned long long after_free = 0;
    kaze_arena_t warmup;

    /* Warm the allocator first: sanitizer bookkeeping grows on the first heap
     * call, and that growth is not a leak in the runtime. */
    if (!kaze_arena_init_heap(&warmup, 4096)) {
        printf("not ok - warmup allocation failed\n");
        return 1;
    }
    kaze_arena_free(&warmup);
    /* stdio allocates its buffer on the first write; that is harness memory,
     * not runtime memory, so it must be resident before the baseline. */
    printf("# asan: starting %llu arena alloc+reset cycles\n", KAZE_ASAN_CYCLES);
    fflush(stdout);
    baseline = (unsigned long long)__sanitizer_get_current_allocated_bytes();
#endif

    if (!kaze_arena_init_heap(&arena, 65536)) {
        printf("not ok - kaze_arena_init_heap failed\n");
        return 1;
    }
    started = kaze_time_ms();

    for (i = 0; i < KAZE_ASAN_CYCLES; i++) {
        /* Varying sizes, odd ones included: every block must still land on an
         * 8-byte boundary, which is where a broken cursor would show up. */
        size_t n = (size_t)(i % 97ULL) + 1u;
        unsigned char *block = (unsigned char *)kmalloc(&arena, n);

        if (block == NULL) {
            printf("not ok - kmalloc returned NULL at cycle %llu\n", i);
            return 1;
        }
        if (((uintptr_t)block % 8u) != 0) {
            printf("not ok - unaligned allocation at cycle %llu\n", i);
            return 1;
        }
        block[0] = (unsigned char)(i & 0xFFULL);
        if (n > 1u) {
            block[n - 1u] = (unsigned char)((i >> 8) & 0xFFULL);
        }

        if ((i % 10000ULL) == 0ULL) {
            kaze_map_t *m = map_new(&arena);
            kaze_vec_t *v = vec_new_vals(&arena, 8);
            int k;

            if (m == NULL || v == NULL) {
                printf("not ok - container header allocation failed at cycle %llu\n", i);
                return 1;
            }
            for (k = 0; k < 32; k++) {
                char keybuf[24];
                kaze_val_t val = kaze_val_number((kaze_float_t)k);

                snprintf(keybuf, sizeof keybuf, "key%02d", k);
                if (!map_set(&arena, m, str_from_cstr(&arena, keybuf), val)) {
                    printf("not ok - map_set failed at cycle %llu\n", i);
                    return 1;
                }
                if (!vec_push(&arena, v, &val)) {
                    printf("not ok - vec_push failed at cycle %llu\n", i);
                    return 1;
                }
            }
            if (map_len(m) != 32u || vec_len(v) != 32u) {
                printf("not ok - container lengths drifted at cycle %llu\n", i);
                return 1;
            }
            if (!map_get(m, str_from_cstr(&arena, "key17"), NULL)) {
                printf("not ok - map_get lost a key at cycle %llu\n", i);
                return 1;
            }
            container_builds++;
        }

        kaze_arena_reset(&arena);
        if (kaze_arena_used(&arena) != 0 || kaze_arena_failed(&arena)) {
            printf("not ok - reset left state behind at cycle %llu\n", i);
            return 1;
        }
    }

    elapsed = kaze_time_ms() - started;
    kaze_arena_free(&arena);
    printf("# asan: %llu alloc+reset cycles, %llu container builds, %llu ms\n",
           KAZE_ASAN_CYCLES, container_builds, (unsigned long long)elapsed);
    printf("ok - %llu arena alloc + bulk-reset cycles, no byte was ever misaligned\n",
           KAZE_ASAN_CYCLES);
#ifdef KAZE_HAVE_ALLOC_IFACE
    after_free = (unsigned long long)__sanitizer_get_current_allocated_bytes();
    printf("# asan heap: %llu bytes before init_heap, %llu bytes after kaze_arena_free\n",
           baseline, after_free);
    if (after_free > baseline) {
        printf("not ok - the arena leaked %llu heap bytes\n", after_free - baseline);
        return 1;
    }
    printf("ok - the arena returned every heap byte it took (leak counter %llu -> %llu)\n",
           baseline, after_free);
#endif
    return 0;
}

