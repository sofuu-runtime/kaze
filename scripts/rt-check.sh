static void test_types(void)
{
    check(sizeof(kaze_int_t) == sizeof(void *), "kaze_int_t matches the pointer width");
    check(sizeof(kaze_uint_t) == sizeof(kaze_int_t), "kaze_uint_t matches kaze_int_t");
    check(sizeof(u8) == 1 && sizeof(u16) == 2 && sizeof(u32) == 4 && sizeof(u64) == 8,
          "fixed-width unsigned types are 1/2/4/8 bytes");
    check(sizeof(i8) == 1 && sizeof(i16) == 2 && sizeof(i32) == 4 && sizeof(i64) == 8,
          "fixed-width signed types are 1/2/4/8 bytes");
    check(sizeof(f32) == 4 && sizeof(f64) == 8, "f32/f64 are IEEE-754 binary32/binary64");
    check(sizeof(kaze_bool_t) == 1, "kaze_bool_t is one byte");
    check(sizeof(kaze_val_payload_t) >= 2u * sizeof(void *),
          "the value payload can hold a pointer plus a length");
    printf("# sizes: pointer=%zu kaze_int_t=%zu kaze_float_t=%zu str=%zu vec=%zu val=%zu payload=%zu map_entry=%zu arena=%zu\n",
           sizeof(void *), sizeof(kaze_int_t), sizeof(kaze_float_t), sizeof(kaze_str_t),
           sizeof(kaze_vec_t), sizeof(kaze_val_t), sizeof(kaze_val_payload_t),
           sizeof(kaze_map_entry_t), sizeof(kaze_arena_t));
}

static void test_arena(void)
{
    /* Deliberately misaligned: base + 1 forces the arena to align the base and
     * still hand out 8-byte aligned blocks. */
    static unsigned char raw[4104];
    kaze_arena_t arena;
    size_t i;
    bool aligned = true;
    bool ordered = true;
    uintptr_t previous = 0;
    size_t capacity;

    kaze_arena_init(&arena, raw + 1, sizeof raw - 1u);
    capacity = kaze_arena_capacity(&arena);
    check(capacity >= 4090 && capacity <= sizeof raw, "a misaligned caller buffer costs at most 7 bytes");
    check(kaze_arena_used(&arena) == 0, "a fresh arena starts at offset zero");

    for (i = 0; i < 40; i++) {
        void *p = kmalloc(&arena, i + 1u);
        if (p == NULL || ((uintptr_t)p % 8u) != 0) {
            aligned = false;
        }
        if (p != NULL) {
            if (previous != 0 && (uintptr_t)p <= previous) {
                ordered = false;
            }
            previous = (uintptr_t)p;
        }
    }
    check(aligned, "every kmalloc result is 8-byte aligned (odd sizes included)");
    check(ordered, "a bump allocator never hands out overlapping blocks");
    check(kaze_arena_used(&arena) >= 40, "kaze_arena_used tracks the consumed bytes");

    {
        size_t before = kaze_arena_used(&arena);
        void *zero = kmalloc(&arena, 0);
        check(zero != NULL && kaze_arena_used(&arena) == before,
              "a zero-size request returns a pointer and consumes nothing");
    }

    /* OOM: a request larger than the whole arena. */
    {
        kaze_arena_t small;
        unsigned char small_buf[64];
        void *big;

        kaze_arena_init(&small, small_buf, sizeof small_buf);
        reset_capture();
        big = kmalloc(&small, 4096);
        check(big == NULL, "kmalloc returns NULL when the request cannot fit");
        check(kaze_arena_failed(&small), "the OOM is recorded in arena->failed");
        check(trapped_with("E_KAZE_OOM"), "the OOM trap reports E_KAZE_OOM");
        check(kaze_arena_used(&small) == 0, "a failed allocation leaves the cursor untouched");
        check(kmalloc(&small, 16) != NULL, "a smaller request still succeeds after an OOM");

        reset_capture();
        check(!kaze_arena_require(&small, 4096), "kaze_arena_require refuses an oversized plan");
        check(trapped_with("E_KAZE_OOM"), "kaze_arena_require reports E_KAZE_OOM");
        check(kaze_arena_require(&small, 8), "kaze_arena_require accepts a plan that fits");

        kaze_arena_reset(&small);
        check(kaze_arena_used(&small) == 0 && !kaze_arena_failed(&small),
              "kaze_arena_reset clears the cursor and the OOM flag");
        check(kaze_arena_capacity(&small) == sizeof small_buf,
              "kaze_arena_reset retains the capacity");
        check(kmalloc(&small, sizeof small_buf - 8u) != NULL,
              "the whole capacity is reusable after a reset");
    }

#ifndef KAZE_NO_HEAP
    {
        kaze_arena_t heap;
        bool inited = kaze_arena_init_heap(&heap, 1024);
        check(inited, "kaze_arena_init_heap binds a heap block");
        check(kaze_arena_capacity(&heap) == 1024, "the heap arena reports the requested capacity");
        check(kmalloc(&heap, 64) != NULL, "the heap arena allocates");
        kaze_arena_free(&heap);
        check(kaze_arena_capacity(&heap) == 0 && kaze_arena_used(&heap) == 0,
              "kaze_arena_free releases the block and clears the header");
    }
#endif
}

static void test_arithmetic(void)
{
    kaze_int_t out = 7;
    kaze_float_t fout = (kaze_float_t)7;

    check(kaze_add_checked(2, 3, &out) && out == 5, "add_checked accepts 2 + 3");
    check(!kaze_add_checked(KAZE_INT_MAX, 1, &out) && out == 0,
          "add_checked rejects KAZE_INT_MAX + 1 and zeroes out");
    check(!kaze_add_checked(KAZE_INT_MIN, -1, &out), "add_checked rejects KAZE_INT_MIN - 1");
    check(kaze_sub_checked(2, 3, &out) && out == -1, "sub_checked accepts 2 - 3");
    check(!kaze_sub_checked(KAZE_INT_MIN, 1, &out), "sub_checked rejects KAZE_INT_MIN - 1");
    check(!kaze_sub_checked(KAZE_INT_MAX, -1, &out), "sub_checked rejects KAZE_INT_MAX + 1");
    check(kaze_mul_checked(-3, -4, &out) && out == 12, "mul_checked accepts -3 * -4");
    check(kaze_mul_checked(KAZE_INT_MAX, 1, &out) && out == KAZE_INT_MAX,
          "mul_checked accepts KAZE_INT_MAX * 1");
    check(!kaze_mul_checked(KAZE_INT_MAX, 2, &out), "mul_checked rejects KAZE_INT_MAX * 2");
    check(!kaze_mul_checked(KAZE_INT_MIN, -1, &out), "mul_checked rejects KAZE_INT_MIN * -1");
    check(kaze_div_checked(7, 2, &out) && out == 3, "div_checked accepts 7 / 2");
    check(kaze_div_checked(-7, 2, &out) && out == -3, "div_checked truncates toward zero");
    check(!kaze_div_checked(7, 0, &out), "div_checked rejects a zero divisor");
    check(kaze_mod_checked(7, 2, &out) && out == 1, "mod_checked accepts 7 % 2");
    check(!kaze_mod_checked(7, 0, &out), "mod_checked rejects a zero divisor");
    check(kaze_neg_checked(5, &out) && out == -5, "neg_checked accepts 5");
    check(!kaze_neg_checked(KAZE_INT_MIN, &out), "neg_checked rejects KAZE_INT_MIN");
    check(kaze_float_div_checked((kaze_float_t)1, (kaze_float_t)4, &fout) &&
              fout == (kaze_float_t)0.25,
          "float_div_checked accepts 1 / 4");
    check(!kaze_float_div_checked((kaze_float_t)1, (kaze_float_t)0, &fout),
          "float_div_checked rejects a zero divisor");

    reset_capture();
    check(kaze_add(KAZE_INT_MAX, 1) == 0, "kaze_add returns its fallback 0 after overflow");
    check(trapped_with("E_KAZE_OVERFLOW"), "kaze_add traps E_KAZE_OVERFLOW");
    reset_capture();
    check(kaze_sub(KAZE_INT_MIN, 1) == 0, "kaze_sub returns its fallback 0 after overflow");
    check(trapped_with("E_KAZE_OVERFLOW"), "kaze_sub traps E_KAZE_OVERFLOW");
    reset_capture();
    check(kaze_mul(KAZE_INT_MAX, 2) == 0, "kaze_mul returns its fallback 0 after overflow");
    check(trapped_with("E_KAZE_OVERFLOW"), "kaze_mul traps E_KAZE_OVERFLOW");
    reset_capture();
    check(kaze_div(1, 0) == 0, "kaze_div returns its fallback 0 after divide by zero");
    check(trapped_with("E_KAZE_DIV0"), "kaze_div traps E_KAZE_DIV0");
    reset_capture();
    check(kaze_mod(1, 0) == 0, "kaze_mod returns its fallback 0 after modulo by zero");
    check(trapped_with("E_KAZE_DIV0"), "kaze_mod traps E_KAZE_DIV0");
    reset_capture();
    check(kaze_neg(KAZE_INT_MIN) == 0, "kaze_neg returns its fallback 0 after overflow");
    check(trapped_with("E_KAZE_OVERFLOW"), "kaze_neg traps E_KAZE_OVERFLOW");
    reset_capture();
    check(kaze_float_div((kaze_float_t)1, (kaze_float_t)0) == (kaze_float_t)0,
          "kaze_float_div returns its fallback 0 after a zero divisor");
    check(trapped_with("E_KAZE_DIV0"), "kaze_float_div traps E_KAZE_DIV0");

    {
        /* Build an infinity with arithmetic instead of a math.h constant, so
         * the test exercises the non-finite branch on every libc. */
        kaze_float_t huge = (kaze_float_t)1;
        int i;
        for (i = 0; i < 1200; i++) {
            huge *= (kaze_float_t)2;
        }
        reset_capture();
        check(!kaze_float_div_checked(huge, (kaze_float_t)1, &fout),
              "float_div_checked rejects a non-finite result");
        check(kaze_float_div(huge, (kaze_float_t)1) == (kaze_float_t)0,
              "kaze_float_div returns its fallback 0 for a non-finite result");
        check(trapped_with("E_KAZE_MATH"), "kaze_float_div traps E_KAZE_MATH");
    }
}

static void test_values(void)
{
    /* Large enough for 200 map keys across every rehash the growth policy
     * performs (each rehash abandons the previous entry array in the arena). */
    static unsigned char raw[262144];
    kaze_arena_t arena;
    kaze_str_t hello;
    kaze_str_t world;
    kaze_str_t joined;
    kaze_str_t empty;
    kaze_str_t copied;

    kaze_arena_init(&arena, raw, sizeof raw);

    /* Strings */
    hello = str_from_cstr(&arena, "hello");
    world = str_from_cstr(&arena, "world");
    empty = str_from_cstr(&arena, "");
    check(hello.len == 5 && hello.ptr != NULL, "str_from_cstr copies the bytes and keeps the length");
    check(str_eq(hello, str_from_cstr(&arena, "hello")), "str_eq sees equal contents");
    check(!str_eq(hello, world), "str_eq sees different lengths");
    check(empty.len == 0 && empty.ptr == NULL, "the empty string is the null slice");
    check(str_eq(empty, str_from_cstr(&arena, "")), "two empty strings compare equal");
    joined = str_concat(&arena, hello, world);
    check(joined.len == 10 && strcmp(str_cstr(&arena, joined), "helloworld") == 0,
          "str_concat joins two slices in order");
    {
        kaze_str_t prefix = str_from_cstr(&arena, "kaz");
        kaze_str_t suffix = str_from_cstr(&arena, "e");
        joined = str_concat(&arena, prefix, suffix);
        check(str_eq(joined, str_from_cstr(&arena, "kaze")), "str_concat works for unequal lengths");
    }

    /* Vectors of plain ints, grown by doubling. */
    {
        kaze_vec_t *ints = vec_new(&arena, sizeof(int), 0);
        int i;
        bool all_ok = true;
        check(ints != NULL && vec_len(ints) == 0 && vec_cap(ints) == 0,
              "vec_new starts empty when no capacity is requested");
        for (i = 0; i < 100; i++) {
            int value = i * 3;
            if (!vec_push(&arena, ints, &value)) {
                break;
            }
        }
        check(vec_len(ints) == 100, "vec_push grows to 100 elements");
        check(vec_cap(ints) >= 100, "vec_cap covers the grown length");
        for (i = 0; i < 100; i++) {
            const int *got = (const int *)vec_get(ints, (size_t)i);
            if (got == NULL || *got != i * 3) {
                all_ok = false;
            }
        }
        check(all_ok, "vec_get returns every element in insertion order");
        check(vec_get(ints, 100) == NULL, "vec_get returns NULL one past the end");
        check(vec_get(ints, 9999) == NULL, "vec_get returns NULL far past the end");
    }

    /* A vector of kaze_val_t, the shape lowered code uses for a list. */
    {
        kaze_vec_t *vals = vec_new_vals(&arena, 8);
        kaze_val_t vnum = kaze_val_number((kaze_float_t)42);
        kaze_val_t *slot;
        kaze_val_t vtext = kaze_val_text(hello);
        kaze_val_t vpoint = kaze_val_point((kaze_float_t)1, (kaze_float_t)2, (kaze_float_t)3);
        check(vals != NULL && vec_cap(vals) == 8, "vec_new_vals honours the capacity hint");
        check(vec_push(&arena, vals, &vnum), "vec_push accepts a kaze_val_t");
        check(vec_push(&arena, vals, &vtext), "a text value enters the list");
        check(vec_push(&arena, vals, &vpoint), "a point value enters the list");
        slot = (kaze_val_t *)vec_get(vals, 0);
        check(slot != NULL && slot->kind == KAZE_KIND_NUMBER && slot->as.num == (kaze_float_t)42,
              "the stored number survives the round trip");
        slot = (kaze_val_t *)vec_get(vals, 1);
        check(slot != NULL && slot->kind == KAZE_KIND_TEXT && str_eq(slot->as.text, hello),
              "the stored text keeps its arena slice");
        slot = (kaze_val_t *)vec_get(vals, 2);
        check(slot != NULL && slot->kind == KAZE_KIND_POINT && slot->as.point.z == (kaze_float_t)3,
              "the stored point keeps all three coordinates");
        check(vec_len(vals) == 3, "vec_len agrees with three pushes");
    }

    /* Maps: enough keys to force several rehashes. */
    {
        kaze_map_t *m = map_new(&arena);
        char keybuf[16];
        kaze_val_t v = kaze_val_unit();
        int i;
        bool inserted = true;
        bool all_found = true;
        bool odds_found = true;
        bool deleted_all = true;

        check(m != NULL && map_len(m) == 0, "map_new starts empty");
        for (i = 0; i < 200; i++) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            if (!map_set(&arena, m, str_from_cstr(&arena, keybuf), kaze_val_number((kaze_float_t)i))) {
                inserted = false;
            }
        }
        check(inserted, "map_set accepts 200 distinct keys");
        check(map_len(m) == 200, "map_len counts 200 live keys");
        for (i = 0; i < 200; i++) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            if (!map_get(m, str_from_cstr(&arena, keybuf), &v) || v.kind != KAZE_KIND_NUMBER ||
                v.as.num != (kaze_float_t)i) {
                all_found = false;
            }
        }
        check(all_found, "map_get returns every inserted value");
        check(!map_get(m, str_from_cstr(&arena, "absent"), &v),
              "map_get reports an absent key without trapping");
        check(!map_contains(m, str_from_cstr(&arena, "absent")), "map_contains agrees on absence");
        check(map_contains(m, str_from_cstr(&arena, "k137")), "map_contains finds a present key");

        /* Deleting half the keys leaves tombstones; the other half must still
         * be reachable through the probe chains that cross them. */
        for (i = 0; i < 200; i += 2) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            if (!map_del(m, str_from_cstr(&arena, keybuf))) {
                deleted_all = false;
            }
        }
        check(deleted_all && map_len(m) == 100,
              "map_del removes 100 keys and map_len drops to 100");
        for (i = 1; i < 200; i += 2) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            if (!map_get(m, str_from_cstr(&arena, keybuf), &v)) {
                odds_found = false;
            }
        }
        check(odds_found, "keys behind deleted probe chains are still found");
        for (i = 0; i < 200; i += 2) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            if (map_get(m, str_from_cstr(&arena, keybuf), &v)) {
                all_found = false;
            }
        }
        check(all_found, "deleted keys are no longer found");

        /* Reinsert over tombstones, then confirm the whole set is intact. */
        for (i = 0; i < 200; i += 2) {
            snprintf(keybuf, sizeof keybuf, "k%03d", i);
            (void)map_set(&arena, m, str_from_cstr(&arena, keybuf), kaze_val_number((kaze_float_t)i));
        }
        check(map_len(m) == 200, "reinserting over tombstones restores 200 keys");
        check(map_get(m, str_from_cstr(&arena, "k042"), &v) &&
                  v.as.num == (kaze_float_t)42,
              "a reinserted key returns its new value");

        /* Keys are copied into the arena, so a stack buffer may be reused. */
        {
            char scratch[8];
            memcpy(scratch, "copy", 4);
            copied.ptr = (const uint8_t *)scratch;
            copied.len = 4;
            check(map_set(&arena, m, copied, kaze_val_number((kaze_float_t)7)),
                  "map_set accepts a key from a stack buffer");
            memset(scratch, 'X', sizeof scratch);
            check(map_get(m, str_from_cstr(&arena, "copy"), &v) &&
                      v.as.num == (kaze_float_t)7,
                  "map_set copied the key bytes into the arena");
        }
        check(map_set(&arena, m, empty, kaze_val_bool(true)), "the empty string is a usable key");
        check(map_get(m, empty, &v) && v.kind == KAZE_KIND_BOOL && v.as.b,
              "the empty key round-trips");
        check(!map_del(m, str_from_cstr(&arena, "never-there")),
              "map_del reports false for an absent key");
    }

    /* Value predicates mirror the Rust VM's words. */
    check(!kaze_val_truthy(kaze_val_unit()), "unit is falsy");
    check(kaze_val_truthy(kaze_val_bool(true)) && !kaze_val_truthy(kaze_val_bool(false)),
          "bool truthiness follows the value");
    check(!kaze_val_truthy(kaze_val_number((kaze_float_t)0)) &&
              kaze_val_truthy(kaze_val_number((kaze_float_t)-1)),
          "number truthiness is non-zero");
    check(!kaze_val_truthy(kaze_val_text(empty)) && kaze_val_truthy(kaze_val_text(hello)),
          "text truthiness is non-empty");
