#!/usr/bin/env bash
# cli-dx-gates.sh -- acceptance gates for plan 12 (unified CLI and standalone DX).
#
#   bash scripts/cli-dx-gates.sh
#   KAZE_GATE_NO_BUILD=1 bash scripts/cli-dx-gates.sh
#
# The gate intentionally uses a private copy of the binary.  `bin/kaze` is a
# shared build product in this repository, and concurrent compiler work may
# refresh it while this script runs.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/kaze-cli-gate.XXXXXX")
trap 'rm -rf "$WORK"' EXIT INT TERM

PASS=0
FAIL=0
GATE_BIN="$WORK/kaze"

say()  { printf 'cli-dx: %s\n' "$*"; }
ok()   { PASS=$((PASS + 1)); printf 'PASS  %s\n' "$*"; }
bad()  { FAIL=$((FAIL + 1)); printf 'FAIL  %s\n' "$*"; }

# Run a command with a wanted exit status.  stdout+stderr go to $WORK/last.*.
expect_rc() {
    local want=$1
    shift
    set +e
    "$@" >"$WORK/last.out" 2>"$WORK/last.err"
    local got=$?
    set -e
    if [ "$got" -ne "$want" ]; then
        bad "expected exit $want, got $got: $*"
        sed 's/^/      /' "$WORK/last.out" "$WORK/last.err" | head -20
        return 1
    fi
    return 0
}

require_grep() {
    local pattern=$1 file=$2 label=$3
    if grep -qE "$pattern" "$file"; then
        ok "$label"
    else
        bad "$label"
        sed 's/^/      /' "$file" | head -20
    fi
}

cc_works() {
    command -v "${CC:-cc}" >/dev/null 2>&1
}

# ---------------------------------------------------------------------------
# Step 12.1: build the single binary, then prove it works with no ./bin/ tree.
# ---------------------------------------------------------------------------
if [ "${KAZE_GATE_NO_BUILD:-0}" != "1" ]; then
    say "building the unified binary"
    if ! bash "$ROOT/scripts/build-cli.sh" >"$WORK/build.out" 2>"$WORK/build.err"; then
        bad "build-cli.sh"
        tail -20 "$WORK/build.err" | sed 's/^/      /'
        echo
        echo "cli-dx-gates: $PASS passed, $FAIL failed"
        exit 1
    fi
fi

SOURCE_BIN=${KAZE_GATE_BIN:-$ROOT/bin/kaze}
if [ ! -x "$SOURCE_BIN" ]; then
    bad "no unified binary at $SOURCE_BIN (run scripts/build-cli.sh)"
    exit 1
fi
cp "$SOURCE_BIN" "$GATE_BIN"
chmod 755 "$GATE_BIN"
ok "unified binary built"

if expect_rc 0 "$GATE_BIN" version; then
    if grep -q '^runtime: embedded$' "$WORK/last.out" &&
       grep -q '^backend: c99' "$WORK/last.out"; then
        ok "version reports the embedded runtime and C99 backend"
    else
        bad "version metadata"
        sed 's/^/      /' "$WORK/last.out"
    fi
fi

if expect_rc 0 "$GATE_BIN" --help; then
    require_grep 'USAGE: kaze <command>' "$WORK/last.out" "help prints the command surface"
fi

mkdir -p "$WORK/isolated"
cp "$GATE_BIN" "$WORK/isolated/kaze"
cat >"$WORK/isolated/standalone.kaze" <<'KAZE'
action main() -> num:
    return 7
KAZE

if expect_rc 0 "$WORK/isolated/kaze" check "$WORK/isolated/standalone.kaze"; then
    ok "check works beside no repository tree"
fi
if expect_rc 0 "$WORK/isolated/kaze" run "$WORK/isolated/standalone.kaze"; then
    if [ "$(tail -n 1 "$WORK/last.out")" = "7" ]; then
        ok "run works beside no repository tree"
    else
        bad "isolated run output"
        cat "$WORK/last.out"
    fi
fi
if expect_rc 0 "$WORK/isolated/kaze" emit-c "$WORK/isolated/standalone.kaze"; then
    if grep -q 'Generated by Kaze' "$WORK/last.out"; then
        ok "emit-c works beside no repository tree"
    else
        bad "isolated emit-c output"
    fi
fi

# A normal run removes its scratch directory; only --keep-temps may leave one.
mkdir -p "$WORK/tmp-clean"
if TMPDIR="$WORK/tmp-clean" "$WORK/isolated/kaze" run "$WORK/isolated/standalone.kaze" \
        >"$WORK/clean.out" 2>"$WORK/clean.err" &&
   ! ls -A "$WORK/tmp-clean" | grep -q '^kaze-'; then
    ok "run removes its temporary build directory"
else
    bad "temporary build directory was left behind"
    ls -A "$WORK/tmp-clean" | sed 's/^/      /'
fi

# ---------------------------------------------------------------------------
# Step 12.2: tensor auto-linking, no kaze-tensor-build.sh.
# ---------------------------------------------------------------------------
say "running the tensor auto-link gate"
if expect_rc 0 env -u KAZE_LIB_DIR -u KAZE_STD_DIR -u KAZE_BIN -u KAZE_RT_DIR \
        "$GATE_BIN" run "$ROOT/scripts/phase12/kaze/tensor_exec.kaze"; then
    if [ "$(tail -n 1 "$WORK/last.out")" = "172" ]; then
        ok "tensor_exec prints 172 with automatic linking"
    else
        bad "tensor_exec output"
        cat "$WORK/last.out"
    fi
fi

# ---------------------------------------------------------------------------
# Step 12.3: exit codes, JSON diagnostics, formatting, verification and tests.
# ---------------------------------------------------------------------------
say "checking command and exit-code compliance"
BAD="$ROOT/tests/fixtures/strict/div_no_fallback.kaze"
GOOD="$ROOT/examples/hello.kaze"

if expect_rc 1 "$GATE_BIN" check "$BAD"; then
    require_grep 'E_KAZE_' "$WORK/last.out" "check exits 1 with an E_KAZE diagnostic"
fi
if expect_rc 0 "$GATE_BIN" check "$GOOD"; then
    require_grep 'check: ok' "$WORK/last.out" "check exits 0 on valid code"
fi
if expect_rc 2 "$GATE_BIN" check "$WORK/does-not-exist.kaze"; then
    ok "check exits 2 on a missing file"
fi
if expect_rc 1 "$GATE_BIN" check --json "$BAD"; then
    if python3 - "$WORK/last.out" <<'PY'
import json, sys
doc = json.load(open(sys.argv[1]))
assert doc["ok"] is False
assert doc["files"][0]["diagnostics"]
assert doc["files"][0]["diagnostics"][0]["code"].startswith("E_KAZE_")
PY
    then
        ok "check --json is machine-readable"
    else
        bad "check --json payload"
        cat "$WORK/last.out"
    fi
fi

# A deliberately over-indented file: relying on a repository source being
# unformatted makes the gate depend on a different subsystem's state.
printf 'action main() -> num:\n        return 1\n' >"$WORK/format.kaze"
if expect_rc 1 "$GATE_BIN" fmt --check "$WORK/format.kaze"; then
    ok "fmt --check exits 1 before writing"
fi
if expect_rc 0 "$GATE_BIN" fmt -w "$WORK/format.kaze"; then
    ok "fmt -w succeeds"
fi
if expect_rc 0 "$GATE_BIN" fmt --check "$WORK/format.kaze"; then
    ok "fmt --check is idempotent"
fi
cp "$WORK/format.kaze" "$WORK/format.noext"
if "$GATE_BIN" fmt "$WORK/format.noext" >"$WORK/fmt1" 2>"$WORK/fmt1.err" &&
   "$GATE_BIN" fmt "$WORK/fmt1" >"$WORK/fmt2" 2>"$WORK/fmt2.err" &&
   cmp -s "$WORK/fmt1" "$WORK/fmt2"; then
    ok "fmt accepts an explicit file without a .kaze suffix"
else
    bad "fmt extensionless round trip"
    cat "$WORK/fmt1.err" "$WORK/fmt2.err" | head -10
fi
if expect_rc 0 "$GATE_BIN" verify "$ROOT/scripts/phase16/contract_ok.kaze"; then
    require_grep 'proven: 1' "$WORK/last.out" "verify certifies a valid contract"
fi
if expect_rc 1 "$GATE_BIN" verify "$ROOT/scripts/phase16/contract_bad.kaze"; then
    ok "verify exits 1 on an unproven contract"
fi
if expect_rc 0 "$GATE_BIN" emit-ir "$WORK/isolated/standalone.kaze"; then
    require_grep '^func main' "$WORK/last.out" "emit-ir prints lowered IR"
fi
if expect_rc 0 "$GATE_BIN" compile "$WORK/isolated/standalone.kaze"; then
    require_grep '^4b415a45' "$WORK/last.out" "compile prints a KAZE bytecode module"
fi
cat >"$WORK/trap.kaze" <<'KAZE'
action main(x: num) -> num:
    guard x > 0
    return x
KAZE
if expect_rc 70 "$GATE_BIN" run "$WORK/trap.kaze" --arg x=0; then
    require_grep 'E_KAZE_GUARD' "$WORK/last.err" "run preserves a runtime trap as exit 70"
fi
if expect_rc 0 "$GATE_BIN" test; then
    expected_suites=$(find "$ROOT/tests/stdlib" -name '*_test.kaze' | wc -l | tr -d ' ')
    for lib in "$ROOT"/lib/*.kaze; do
        [ -f "$lib" ] && grep -q '^test ' "$lib" && expected_suites=$((expected_suites + 1))
    done
    if grep -q "kaze test: $expected_suites passed, 0 failed" "$WORK/last.out"; then
        ok "kaze test runs all $expected_suites standard library suites cleanly"
    else
        bad "kaze test summary (expected $expected_suites suites)"
        tail -5 "$WORK/last.out"
    fi
fi

# The REPL keeps definitions in a buffer and evaluates `= expression` in a
# fresh process; both halves are part of the standalone command surface.
if printf 'action greet() -> text:\n    return "hi"\n\n= greet()\n:quit\n' |
        "$GATE_BIN" repl >"$WORK/repl.out" 2>"$WORK/repl.err"; then
    if grep -q '^hi$' "$WORK/repl.out"; then
        ok "repl keeps a definition and evaluates an expression"
    else
        bad "repl output"
        cat "$WORK/repl.out" "$WORK/repl.err" | head -10 | sed 's/^/      /'
    fi
else
    bad "repl round trip"
    cat "$WORK/repl.out" "$WORK/repl.err" | head -10 | sed 's/^/      /'
fi

# ---------------------------------------------------------------------------
# Step 12.4: install into an isolated prefix and use it from a fresh directory.
# ---------------------------------------------------------------------------
say "installing into an isolated prefix"
PREFIX="$WORK/prefix"
STAGE="$WORK/stage"
if expect_rc 0 env PREFIX="$PREFIX" DESTDIR="$STAGE" KAZE_INSTALL_BIN="$GATE_BIN" \
        bash "$ROOT/scripts/install.sh" --no-build; then
    ok "install.sh completes"
else
    bad "install.sh"
fi

INSTALLED="$STAGE$PREFIX/bin/kaze"
if [ -x "$INSTALLED" ]; then
    ok "installed binary exists at $PREFIX/bin/kaze"
else
    bad "installed binary missing"
fi

mkdir -p "$WORK/sandbox" "$WORK/home" "$WORK/tmp"
CLEAN_ENV=(env -i
    PATH=/usr/bin:/bin:/usr/sbin:/sbin:/usr/local/bin
    HOME="$WORK/home"
    TMPDIR="$WORK/tmp"
    LANG=C)

if [ -x "$INSTALLED" ]; then
    (
        cd "$WORK/sandbox"
        if "${CLEAN_ENV[@]}" "$INSTALLED" init demo >"$WORK/init.out" 2>"$WORK/init.err"; then
            echo "init ok" >"$WORK/step4.init"
        else
            echo "init failed" >"$WORK/step4.init"
            cat "$WORK/init.out" "$WORK/init.err" >>"$WORK/step4.init"
        fi
    )
    require_grep 'init ok' "$WORK/step4.init" "kaze init in a fresh directory"

    (
        cd "$WORK/sandbox/demo"
        set +e
        "${CLEAN_ENV[@]}" "$INSTALLED" check src/main.kaze >"$WORK/check4.out" 2>&1
        printf 'check=%s\n' "$?" >"$WORK/step4.check"
        "${CLEAN_ENV[@]}" "$INSTALLED" verify src/main.kaze >"$WORK/verify4.out" 2>&1
        printf 'verify=%s\n' "$?" >>"$WORK/step4.check"
        "${CLEAN_ENV[@]}" "$INSTALLED" run src/main.kaze >"$WORK/run4.out" 2>&1
        printf 'run=%s\n' "$?" >>"$WORK/step4.check"
        "${CLEAN_ENV[@]}" "$INSTALLED" build src/main.kaze -o app >"$WORK/build4.out" 2>&1
        printf 'build=%s\n' "$?" >>"$WORK/step4.check"
        ./app >"$WORK/app4.out" 2>&1
        printf 'app=%s\n' "$?" >>"$WORK/step4.check"
        set -e
    )
    if grep -q '^check=0$' "$WORK/step4.check" &&
       grep -q '^verify=0$' "$WORK/step4.check" &&
       grep -q '^run=0$' "$WORK/step4.check" &&
       grep -q '^build=0$' "$WORK/step4.check" &&
       grep -q '^app=0$' "$WORK/step4.check" &&
       [ "$(tail -n 1 "$WORK/run4.out")" = "5" ] &&
       [ "$(tail -n 1 "$WORK/app4.out")" = "5" ]; then
        ok "installed binary checks, verifies, runs and builds in a fresh directory"
    else
        bad "fresh-directory workflow"
        sed 's/^/      /' "$WORK/step4.check"
        cat "$WORK/check4.out" "$WORK/verify4.out" "$WORK/run4.out" "$WORK/build4.out" | head -20 | sed 's/^/      /'
    fi

    # An arbitrary PREFIX is not one of the compiler's conventional stdlib
    # roots, so this proves the installed binary publishes share/kaze/std.
    cat >"$WORK/sandbox/stdlib.kaze" <<'KZ'
needs: log
use "std/json"

action main() -> num:
    let doc = json_parse("{\"ok\":true}")
    log "json loaded"
    return 0
KZ
    if "${CLEAN_ENV[@]}" "$INSTALLED" run "$WORK/sandbox/stdlib.kaze" \
            >"$WORK/stdlib4.out" 2>&1; then
        if grep -q 'json loaded' "$WORK/stdlib4.out"; then
            ok "installed binary resolves use \"std/...\" outside the checkout"
        else
            bad "installed stdlib output"
            cat "$WORK/stdlib4.out" | head -10 | sed 's/^/      /'
        fi
    else
        bad "installed binary cannot resolve use \"std/...\""
        cat "$WORK/stdlib4.out" | head -10 | sed 's/^/      /'
    fi
fi

# ---------------------------------------------------------------------------
# Incremental .kaze-cache/, --target forwarding, and compiler/lsp.kaze delegation.
# ---------------------------------------------------------------------------
mkdir -p "$WORK/inc"
cat >"$WORK/inc/a.kaze" <<'KZ'
pub action alpha() -> num:
    return 10
KZ
cat >"$WORK/inc/b.kaze" <<'KZ'
pub action beta() -> num:
    return 32
KZ
cat >"$WORK/inc/main.kaze" <<'KZ'
use "./a.kaze" as a
use "./b.kaze" as b

action main() -> num:
    return a.alpha() + b.beta()
KZ
if "$GATE_BIN" build "$WORK/inc/main.kaze" -o "$WORK/inc/prog" >"$WORK/inc1.out" 2>&1 &&
   [ -d "$WORK/inc/.kaze-cache" ] &&
   grep -q '3 modules, 3 compiled, 0 cached' "$WORK/inc1.out" &&
   [ "$("$WORK/inc/prog")" = "42" ]; then
    printf '\n# warm rebuild comment\n' >>"$WORK/inc/a.kaze"
    if "$GATE_BIN" build "$WORK/inc/main.kaze" -o "$WORK/inc/prog" >"$WORK/inc2.out" 2>&1 &&
       grep -q '3 modules, 0 compiled, 3 cached' "$WORK/inc2.out" &&
       [ "$("$WORK/inc/prog")" = "42" ]; then
        perl -pi -e 's/return 10/return (10 + 1)/' "$WORK/inc/a.kaze"
        if "$GATE_BIN" build "$WORK/inc/main.kaze" -o "$WORK/inc/prog" >"$WORK/inc3.out" 2>&1 &&
           grep -q '3 modules, 1 compiled, 2 cached' "$WORK/inc3.out" &&
           [ "$("$WORK/inc/prog")" = "43" ]; then
            ok "bin/kaze build uses .kaze-cache/ semantically"
        else
            bad "bin/kaze incremental semantic rebuild"
            cat "$WORK/inc3.out" | head -10
        fi
    else
        bad "bin/kaze incremental cosmetic reuse"
        cat "$WORK/inc2.out" | head -10
    fi
else
    bad "bin/kaze incremental cold build"
    cat "$WORK/inc1.out" | head -10
fi

if expect_rc 2 "$GATE_BIN" build --target=arm64 "$WORK/inc/main.kaze" -o "$WORK/inc/tfail"; then
    require_grep 'requires --backend=native' "$WORK/last.err" "c99 rejects non-native --target cleanly"
fi
if [ -x "$ROOT/bin/kaze-native" ] && [ "$(uname -s)" = "Darwin" ] && [ "$(uname -m)" = "arm64" ]; then
    if KAZE_NATIVE_BIN="$ROOT/bin/kaze-native" "$GATE_BIN" run --backend=native --target=arm64_apple \
            "$WORK/inc/main.kaze" >"$WORK/nat.out" 2>&1 &&
       [ "$(tail -n 1 "$WORK/nat.out")" = "43" ]; then
        ok "kaze run forwards --target=arm64_apple to kaze-native"
    else
        bad "kaze run --backend=native --target=arm64_apple"
        cat "$WORK/nat.out" | head -10
    fi
fi

if python3 - "$GATE_BIN" "$WORK/inc" <<'PY'
import json, os, subprocess, sys

def frame(m):
    b = json.dumps(m).encode("utf-8")
    return f"Content-Length: {len(b)}\r\n\r\n".encode("ascii") + b

def decode(buf):
    out, i = [], 0
    while i < len(buf):
        j = buf.find(b"\r\n\r\n", i)
        if j < 0:
            break
        hdr = buf[i:j].decode("ascii")
        cl = [int(l.split(":")[1].strip()) for l in hdr.splitlines() if l.lower().startswith("content-length:")][0]
        out.append(json.loads(buf[j+4:j+4+cl].decode("utf-8")))
        i = j + 4 + cl
    return out

gate_bin, inc_dir = sys.argv[1], sys.argv[2]
main_path = os.path.join(inc_dir, "main.kaze")
src = 'use "./a.kaze" as a\n\npub action twice(x: num) -> num:\n    return a.alpha() + x\n\naction main() -> num:\n    return twice(32)\n'
uri = "file://" + main_path
payload = b"".join(frame(m) for m in [
    {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {}},
    {"jsonrpc": "2.0", "method": "textDocument/didOpen", "params": {"textDocument": {"uri": uri, "languageId": "kaze", "version": 1, "text": src}}},
    {"jsonrpc": "2.0", "id": 2, "method": "textDocument/hover", "params": {"textDocument": {"uri": uri}, "position": {"line": 6, "character": 12}}},
    {"jsonrpc": "2.0", "id": 3, "method": "textDocument/definition", "params": {"textDocument": {"uri": uri}, "position": {"line": 6, "character": 12}}},
    {"jsonrpc": "2.0", "id": 4, "method": "shutdown", "params": None},
    {"jsonrpc": "2.0", "method": "exit"},
])
r = subprocess.run([gate_bin, "lsp"], input=payload, capture_output=True, timeout=15)
assert r.returncode == 0, r.stderr
replies = decode(r.stdout)
diags = [m for m in replies if m.get("method") == "textDocument/publishDiagnostics"]
assert diags and diags[0]["params"]["diagnostics"] == [], diags
hover = [m for m in replies if m.get("id") == 2][0]["result"]
assert "action twice(x: num)" in hover["contents"]["value"], hover
defn = [m for m in replies if m.get("id") == 3][0]["result"]
assert defn["range"]["start"]["line"] == 2 and defn["range"]["start"]["character"] == 11, defn
PY
then
    ok "kaze lsp delegates hover/definition to compiler/lsp.kaze with multi-file diagnostics"
else
    bad "kaze lsp delegation"
fi

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
echo
if [ "$FAIL" -eq 0 ]; then
    echo "cli-dx-gates: $PASS passed, 0 failed"
    exit 0
fi
echo "cli-dx-gates: $PASS passed, $FAIL failed"
exit 1
