#!/usr/bin/env python3
"""Generate dist/kaze_embedded_rt.h -- the runtime sources carried by `kaze`.

The unified CLI must work after a single executable is copied somewhere with no
`dist/` directory beside it.  The C driver therefore carries every runtime
translation unit it may need as a C string and materialises the two or three
files a particular build asks for in a temporary directory.

The generated header is intentionally plain C99: an array of {name, bytes,
length} records and a static table.  Sources are split into short adjacent
string literals so no compiler sees a multi-kilobyte source line.

    python3 scripts/gen-embedded-rt.py            # write dist/kaze_embedded_rt.h
    python3 scripts/gen-embedded-rt.py --check    # exit 1 when stale
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")
OUT = os.path.join(DIST, "kaze_embedded_rt.h")

# Everything the emitted C can include, plus the SITL host that is textually
# included when a program is built with KAZE_SITL_LINK.  Order is not
# significant; the CLI asks for files by name.
FILES = [
    "kaze_rt.h",
    "kaze_rt.c",
    "kaze_tensor.h",
    "kaze_tensor.c",
    "kaze_quant.h",
    "kaze_quant.c",
    "kaze_gguf.c",
    "kaze_llama.c",
    "kaze_tokenizer.c",
    "kaze_autograd.c",
    "kaze_http.h",
    "kaze_mavlink.h",
    "kaze_mavlink.c",
    "kaze_sitl_client.c",
    "kaze_metal.h",
    "kaze_metal.m",
    "kaze_blas.h",
    "kaze_blas.c",
]


def c_literal(data: bytes) -> str:
    """Return the file body as adjacent, escaped C string literals."""
    pieces = []
    current = []
    for byte in data:
        if byte == 0x22:          # "
            current.append('\\"')
        elif byte == 0x5C:        # backslash
            current.append("\\\\")
        elif byte == 0x0A:        # newline
            current.append("\\n")
        elif byte == 0x0D:
            current.append("\\r")
        elif byte == 0x09:
            current.append("\\t")
        elif 0x20 <= byte <= 0x7E:
            current.append(chr(byte))
        else:
            # Octal, not hex: the next byte may be a hex digit.  The value is
            # a byte, so a three-digit octal escape is unambiguous.
            current.append("\\%03o" % byte)
        # Keep every physical source line short enough for conservative C
        # compilers while escaping never splits a byte.
        if len("".join(current)) >= 96:
            pieces.append('"' + "".join(current) + '"')
            current = []
    if current or not pieces:
        pieces.append('"' + "".join(current) + '"')
    return "\n    ".join(pieces)


def render() -> bytes:
    lines = []
    lines.append("/* kaze_embedded_rt.h -- generated by scripts/gen-embedded-rt.py.")
    lines.append(" *")
    lines.append(" * The unified `kaze` executable carries its runtime sources.  Do not")
    lines.append(" * edit this file; edit the dist sources and headers, or the generator, then run")
    lines.append(" * scripts/build-cli.sh (which invokes the generator). */")
    lines.append("#ifndef KAZE_EMBEDDED_RT_H")
    lines.append("#define KAZE_EMBEDDED_RT_H")
    lines.append("")
    lines.append("typedef struct kaze_embedded_file {")
    lines.append("    const char *name;")
    lines.append("    const char *data;")
    lines.append("    unsigned long size;")
    lines.append("} kaze_embedded_file;")
    lines.append("")
    lines.append("struct kaze_embedded_blob {")
    lines.append("    const char *name;")
    lines.append("    const char *data;")
    lines.append("    unsigned long size;")
    lines.append("};")
    lines.append("")
    for i, name in enumerate(FILES):
        path = os.path.join(DIST, name)
        if not os.path.isfile(path):
            raise SystemExit("gen-embedded-rt: missing %s" % path)
        with open(path, "rb") as f:
            data = f.read()
        ident = "kaze_emb_%d" % i
        lines.append("static const char %s[] =" % ident)
        lines.append("    " + c_literal(data) + ";")
        lines.append("")
    lines.append("static const struct kaze_embedded_blob kaze_embedded_blobs[] = {")
    for i, name in enumerate(FILES):
        ident = "kaze_emb_%d" % i
        lines.append('    { "%s", %s, sizeof(%s) - 1 },' % (name, ident, ident))
    lines.append("};")
    lines.append("")
    lines.append("#define KAZE_EMBEDDED_BLOB_COUNT %d" % len(FILES))
    lines.append("")
    lines.append("#endif /* KAZE_EMBEDDED_RT_H */")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, "rb") as f:
                current = f.read()
        except OSError:
            current = b""
        if current != content:
            print("gen-embedded-rt: %s is STALE" % OUT, file=sys.stderr)
            return 1
        print("gen-embedded-rt: %s is current" % OUT)
        return 0
    tmp = OUT + ".tmp"
    with open(tmp, "wb") as f:
        f.write(content)
    os.replace(tmp, OUT)
    print("gen-embedded-rt: wrote %s (%d bytes)" % (OUT, len(content)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
